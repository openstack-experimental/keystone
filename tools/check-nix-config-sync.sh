# Compare the keystone.conf section headers generated by tools/start-api.sh
# with those in nix/vm-api-test.nix, so the Nix VM test does not silently
# drift from the regular API test setup.
set -euo pipefail
cd "$(dirname "$0")/.."

sections() {
  grep -oE '^ *\[[A-Za-z_.]+\]' "$1" | tr -d ' ' | sort -u
}

# `jws_tokens` is only written by start-api.sh for the optional JWS token
# provider; the Nix test always uses fernet.
if ! diff <(sections tools/start-api.sh | grep -vx '\[jws_tokens\]') \
          <(sections nix/vm-api-test.nix); then
  echo "keystone.conf sections differ between tools/start-api.sh and nix/vm-api-test.nix" >&2
  exit 1
fi
echo "keystone.conf sections in sync"
